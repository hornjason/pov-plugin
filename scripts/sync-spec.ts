#!/usr/bin/env bun
/**
 * Regenerate `specs/POV-SPEC.md` from the canonical copy in DailyBriefDashboard.
 *
 * The plugin needs a REAL copy, not a pointer: a consumer installing it has no
 * `~/Projects/DailyBriefDashboard`, so a reference to that path resolves to
 * nothing and `skills/pov/SKILL.md`'s first instruction becomes a dead link.
 * A copy that nothing compares is how this repo ended up shipping the
 * pre-#1568 spec — the one still claiming the validated reference is a
 * "~90 word" email with no stat tiles, against an artifact that is 111 words
 * with three attributed tiles.
 *
 *   bun scripts/sync-spec.ts            # rewrite the copy
 *   bun scripts/sync-spec.ts --check    # exit 1 if it is stale
 */
import { readFileSync, writeFileSync, existsSync } from 'fs'
import { createHash } from 'crypto'
import { resolve, join } from 'path'

export const CANONICAL_SPEC =
  process.env.POV_CANONICAL_SPEC ??
  join(process.env.HOME ?? '', 'Projects/DailyBriefDashboard/specs/pov-spec.md')

export const DERIVED_SPEC = resolve(import.meta.dir, '..', 'specs', 'POV-SPEC.md')

/**
 * The identities the canonical spec names, replaced before anything ships.
 *
 * `.claude/rules/no-customer-data.md` is the governing rule and it is not
 * negotiable here: this repo is public and installed by other people. The
 * canonical spec was written beside real engagements and names two of them
 * plus the internal issues that drove them, so a VERBATIM copy is not
 * shippable — which the PII gate reported the moment one was generated, and
 * which is the argument for the gate rather than for a more careful author.
 *
 * The rule also says how to resolve it: *"Say what happened without saying
 * who."* Each identity becomes a stable, meaningless label, so every
 * methodological statement survives — a reader still learns that the
 * validated reference email is 111 words and carries three attributed stat
 * tiles — and nothing identifies the account.
 *
 * The mapping is derived from `.pii-identities.local.json`, which is
 * gitignored, so the substitution table is never committed either. A redaction
 * map that lists what it redacts is the allowlist-as-evidence shape recorded
 * in the sibling repo's rules: the document naming the secrets becomes the
 * disclosure.
 */
export function redactionsFrom(localList: string): Array<[RegExp, string]> {
  const { identities = [], trackers = [] } = JSON.parse(localList) as {
    identities?: string[]
    trackers?: string[]
  }
  const esc = (x: string) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  // Longest first, so a name that contains another is replaced whole.
  const sorted = [...identities].sort((a, b) => b.length - a.length)
  return [
    ...sorted.map(
      (name, i) => [new RegExp(`\\b${esc(name)}\\b`, 'gi'), `REFERENCE-ACCOUNT-${String.fromCharCode(65 + i)}`] as [RegExp, string],
    ),
    ...trackers.map(t => [new RegExp(esc(t), 'g'), 'an internal issue'] as [RegExp, string]),
    // Issue references and local research-vault paths are internal routing,
    // meaningless to a consumer, and a standing invitation to go looking.
    [/\*\*GitHub Issue:\*\*[^\n]*\n/g, ''],
    [/\*\*Research vault:\*\*[^\n]*\n/g, ''],
    [/#\d{3,5}/g, 'an internal issue'],
    [/~\/(?:\.claude|Projects)\/[^\s`)]+/g, 'a local path'],
    // Drive file and folder IDs, deliberately the SAME pattern the gate uses
    // rather than a hand-rolled approximation of it. Two patterns for one
    // question is how a redactor and its gate come to disagree, and the one
    // that loses is always the redactor — the gate just reports.
    //
    // A Drive ID is also the single most load-bearing thing in this file: it
    // is a live, resolvable handle to a real customer document, so it leaks
    // the artifact and not merely the name. The canonical spec cites two.
    [DRIVE_ID_RE, 'a Drive file'],
  ]
}

/**
 * Kept identical to `structuralPatterns()` in `test/pov-plugin.test.ts`.
 * `test/spec-drift.test.ts` asserts the two agree, because a copy of a regex
 * is a second decider and this file's whole subject is what copies do.
 */
export const DRIVE_ID_RE = /\b[01][A-Za-z0-9_-]{27,43}\b/g

export function redact(source: string, localList: string): string {
  return redactionsFrom(localList).reduce((text, [re, to]) => text.replace(re, to), source)
}

export function sha256(s: string): string {
  return createHash('sha256').update(s, 'utf8').digest('hex')
}

/** The banner that makes the copy self-describing, and checkable. */
export function derivedHeader(sourceSha: string, bodySha: string): string {
  return [
    '<!-- DERIVED FILE — do not edit here.',
    '',
    'The canonical POV spec lives in DailyBriefDashboard at specs/pov-spec.md.',
    'This copy ships with the plugin because a consumer has no checkout of that',
    'repo; it is regenerated by `bun scripts/sync-spec.ts`, and',
    '`test/spec-drift.test.ts` fails when either hash below stops matching.',
    '',
    `source-sha256: ${sourceSha}`,
    `body-sha256:   ${bodySha}`,
    '-->',
    '',
  ].join('\n')
}

const FRONTMATTER_RE = /^---\n[\s\S]*?\n---\n/
const BANNER_RE = /<!-- DERIVED FILE[\s\S]*?-->\n*/

/**
 * Insert the banner AFTER the YAML frontmatter, never before it.
 *
 * Frontmatter is only frontmatter at byte 0. Prepending an HTML comment to a
 * file that opens with `---` does not produce a document with a note on top;
 * it produces a document with NO frontmatter and a `---` rule in the body.
 * Measured rather than reasoned about: with the banner first, this repo's own
 * `Spec Discovery` and `HYGIENE-2` cases could not find `doc-type` or
 * `updated` in a file that plainly contains both.
 *
 * The failure mode is the one this repo keeps recording — the parser's view of
 * the input silently shrank, and everything downstream read the result as
 * "the field is missing" rather than "the field was not looked for."
 */
export function withBanner(body: string, banner: string): string {
  const fm = body.match(FRONTMATTER_RE)?.[0]
  return fm ? fm + '\n' + banner + body.slice(fm.length) : banner + body
}

/**
 * Everything except the generated banner — the part that must match upstream.
 *
 * Found by REMOVAL rather than by slicing from a marker offset, so it does not
 * care where the banner sits. The previous version took everything after the
 * first `-->`, which silently became wrong the moment the banner moved below
 * the frontmatter: it would have returned the body minus its own frontmatter
 * and hashed that, and the hash would have been perfectly stable and about the
 * wrong bytes.
 */
export function bodyOf(derived: string): string {
  return derived.replace(BANNER_RE, '')
}

export function recordedHashes(derived: string): { source: string | null; body: string | null } {
  return {
    source: derived.match(/source-sha256:\s*([0-9a-f]{64})/)?.[1] ?? null,
    body: derived.match(/body-sha256:\s*([0-9a-f]{64})/)?.[1] ?? null,
  }
}

if (import.meta.main) {
  const check = process.argv.includes('--check')
  if (!existsSync(CANONICAL_SPEC)) {
    console.error(`UNMEASURED — the canonical spec is not on this machine: ${CANONICAL_SPEC}`)
    console.error('Set POV_CANONICAL_SPEC, or run this from a checkout that has DailyBriefDashboard beside it.')
    process.exit(check ? 0 : 1)
  }
  const source = readFileSync(CANONICAL_SPEC, 'utf-8')
  const localList = resolve(import.meta.dir, '..', '.pii-identities.local.json')
  if (!existsSync(localList)) {
    // A refusal, not a pass. Writing an UNREDACTED copy because the identity
    // list is missing is the exact failure the list exists to prevent, and
    // "no identities found" and "no list found" are indistinguishable
    // downstream.
    console.error('REFUSED — .pii-identities.local.json is absent, so nothing can be redacted.')
    process.exit(1)
  }
  const body = redact(source, readFileSync(localList, 'utf-8'))
  const next = withBanner(body, derivedHeader(sha256(source), sha256(body)))
  const current = existsSync(DERIVED_SPEC) ? readFileSync(DERIVED_SPEC, 'utf-8') : ''
  if (check) {
    if (current === next) {
      console.log('specs/POV-SPEC.md is in sync')
      process.exit(0)
    }
    console.error('specs/POV-SPEC.md is STALE — run: bun scripts/sync-spec.ts')
    process.exit(1)
  }
  writeFileSync(DERIVED_SPEC, next)
  console.log(`wrote specs/POV-SPEC.md from ${CANONICAL_SPEC}`)
}
